      if (l.bonus) L.push(`🎁 Бонус: ${l.bonus}`);
      if (l.warranty) L.push(`🛡 ${l.warranty}`);
      L.push('');
      L.push(`💰 ${S.fmt(l.price)} грн`);
      if (l.special || l.isNew) L.push('Спеціальна пропозиція — діє при визначених умовах оплати');
      L.push('');
